// Fallback to English for any missing key
export function t(lang, key) {
  return (translations[lang] ?? translations.en)[key] ?? translations.en[key] ?? key;
}

// Reactive i18n store
import { writable } from 'svelte/store';
export const i18n = writable({ lang: 'en' });

export function setLang(code) {
  i18n.update(s => ({ ...s, lang: code }));
  try { if (typeof localStorage !== 'undefined') localStorage.setItem('ping_lang', code); } catch {}
}

export function loadLang() {
  try {
    if (typeof localStorage === 'undefined') return;
    const saved = localStorage.getItem('ping_lang');
    if (saved && translations[saved]) i18n.update(s => ({ ...s, lang: saved }));
  } catch {}
}
